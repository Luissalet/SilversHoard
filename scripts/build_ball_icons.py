"""Embed canonical assigned-ball icons so the HUD also works in standalone HTML."""
from pathlib import Path
import base64
import hashlib
import io
import json
import subprocess
import httpx
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
def main():
    query = "import {Dex} from '@pkmn/sim'; console.log(JSON.stringify(Dex.items.all().filter(x=>x.isPokeball).map(x=>({id:x.id,name:x.name}))));"
    balls = json.loads(subprocess.check_output(['node','--input-type=module','-e',query],cwd=ROOT,encoding='utf8'))
    folder = ROOT/'art/balls'
    folder.mkdir(exist_ok=True)
    icons, sources = {}, {}
    with httpx.Client(timeout=30,follow_redirects=True) as client:
        for ball in balls:
            id_ = ball['id']
            path = folder/f'{id_}.png'
            slug = ball['name'].lower().replace(' ','-')
            url = f'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/items/{slug}.png'
            if not path.is_file():
                response = client.get(url); response.raise_for_status()
                path.write_bytes(response.content)
            image = Image.open(path); image.verify()
            raw = path.read_bytes()
            with Image.open(path) as source:
                image = source.convert('RGBA')
            bounds = image.getchannel('A').getbbox()
            icon = image.crop(bounds)
            rendered = io.BytesIO()
            icon.save(rendered, 'PNG', optimize=True)
            png = rendered.getvalue()
            icons[id_] = 'data:image/png;base64,'+base64.b64encode(png).decode('ascii')
            sources[id_] = {**ball,'url':url,'sha256':hashlib.sha256(raw).hexdigest(),
                            'icon':{'crop':list(bounds),'size':list(icon.size),'sha256':hashlib.sha256(png).hexdigest()}}
    (folder/'sources.json').write_text(json.dumps({'credit':'Pokemon / Game Freak; item icons distributed by PokeAPI sprites','sources':sources},indent=2),encoding='utf8',newline='\n')
    (ROOT/'client/src/battle/ball-icons.gen.js').write_text('// Generated by scripts/build_ball_icons.py; source credits and SHA in art/balls/sources.json.\nexport default '+json.dumps(icons,separators=(',',':'))+';\n',encoding='utf8',newline='\n')
    print(f'Embedded {len(icons)} assigned-ball icons')

if __name__ == '__main__':
    main()
