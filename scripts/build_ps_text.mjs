// Rebuilds the battle log's official texts: client/src/battle/text/battle-text.gen.js (the English and Spanish (Spain) message
// templates of the battle simulator: every default line plus the messages of each move, ability and item, without descriptions) and
// client/src/battle/text/text-parser.gen.js (the battle client's text parser that fills them in, with its Spanish grammar rules).
//
// Sources (both MIT, © Guangcong Luo and contributors):
//   smogon/pokemon-showdown          data/text/{default,moves,abilities,items,names}.ts and data/text/es/*.ts
//   smogon/pokemon-showdown-client   play.pokemonshowdown.com/src/battle-text-parser.ts (MIT on its own, as its header says)
//
//   node scripts/build_ps_text.mjs                          downloads at the pinned commits
//   node scripts/build_ps_text.mjs --src <folder>           reads <folder>/en/*.ts, <folder>/es/*.ts and <folder>/battle-text-parser.ts
import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tmpdir } from "node:os";
import { transform } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "client", "src", "battle", "text");
const PINS = { server: "3a766f2cfb5e51c1e428cfe87d0dba91a8f01640", client: "cc6f5c24adaaf0a5eb89effbb580516bbf3e7286" };
const TABLES = { default: "DefaultText", moves: "MovesText", abilities: "AbilitiesText", items: "ItemsText" };
const MESSAGE_SKIP = new Set(["desc", "shortDesc", "flavorText"]);

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : "";
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

async function serverFile(lang, name, src, sha) {
  if (src) return readFile(join(src, lang, `${name}.ts`), "utf8");
  const path = lang === "en" ? `data/text/${name}.ts` : `data/text/${lang}/${name}.ts`;
  return fetchText(`https://raw.githubusercontent.com/smogon/pokemon-showdown/${sha}/${path}`);
}

/** Evaluates one TypeScript text table (export const X = {...}) and returns its exports. */
async function load(ts, tag) {
  const { code } = await transform(ts.replace(/^import[^\n]*\n/gm, ""), { loader: "ts", format: "esm", target: "es2020" });
  const dir = join(tmpdir(), "silver-ps-text");
  await mkdir(dir, { recursive: true });
  const file = join(dir, `${tag}-${process.pid}.mjs`);
  await writeFile(file, code, "utf8");
  try {
    return await import(pathToFileURL(file).href);
  } finally {
    await rm(file, { force: true });
  }
}

/** Keeps names and message templates; drops descriptions, empty translations and anything that is not text. */
function messages(entry, top = true) {
  if (!entry || typeof entry !== "object") return null;
  const out = {};
  for (const [k, v] of Object.entries(entry)) {
    if (MESSAGE_SKIP.has(k)) continue;
    if (typeof v === "string" && v) out[k] = v;
    else if (top && /^gen\d$/.test(k) && v && typeof v === "object") {
      const g = messages(v, false);
      if (g && Object.keys(g).length) out[k] = g;
    }
  }
  return out;
}

function table(obj, keepNameOnly) {
  const out = {};
  for (const [id, entry] of Object.entries(obj || {})) {
    const m = messages(entry);
    if (!m) continue;
    if (!keepNameOnly && Object.keys(m).length === 1 && m.name) { out[id] = { name: m.name }; continue; }
    if (Object.keys(m).length) out[id] = m;
  }
  return out;
}

async function language(lang, src, sha) {
  const out = {};
  for (const [file, exportName] of Object.entries(TABLES)) {
    const mod = await load(await serverFile(lang, file, src, sha), `${lang}-${file}`);
    const key = file === "default" ? "Default" : file[0].toUpperCase() + file.slice(1);
    out[key] = table(mod[exportName]);
  }
  const names = await load(await serverFile(lang, "names", src, sha), `${lang}-names`);
  for (const k of ["StatNames", "StatMediumNames", "StatShortNames"]) if (names[k]) out[k] = Object.fromEntries(Object.entries(names[k]).filter(([, v]) => typeof v === "string" && v));
  return out;
}

