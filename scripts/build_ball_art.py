"""Embed the unmodified user-supplied atlas for both the app and standalone battle pages."""
import base64
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "client/src/battle/pokeball-sheet.png"
output = source.with_name("ball-sheet.gen.js")
output.write_text('// Generated by scripts/build_ball_art.py; original atlas preserved unchanged.\nexport default "data:image/png;base64,'
                  + base64.b64encode(source.read_bytes()).decode("ascii") + '";\n', encoding="utf-8", newline="\n")
