"""Build client/src/battle/rt/kenney.gen.js from Kenney's Particle Pack (CC0, https://kenney.nl/assets/particle-pack).

Usage: python scripts/build_kenney.py <folder with the unzipped pack>
Each chosen texture is reduced to 64 px and turned into a white shape on transparency (its alpha kept), so the screen can tint it
to any colour; the module holds them as data URLs, so the playable page has them without a network."""

import base64
import io
import sys
from pathlib import Path

from PIL import Image

PICK = {"glow": "light_01", "smoke": "smoke_04", "spark": "spark_05", "star": "star_06", "flame": "flame_03", "magic": "magic_02",
        "twirl": "twirl_01", "dirt": "dirt_02", "circle": "circle_05", "slash": "slash_02"}


def main(pack: Path) -> None:
    src = pack / "PNG (Transparent)"
    out = ["// Particle textures from Kenney's Particle Pack 1.1 (kenney.nl, CC0), reduced to 64 px for the real-time effects.",
           "// Generated by scripts/build_kenney.py: white shapes on transparency, tinted at draw time (vfx.js).", "export const KENNEY = {"]
    for key, name in PICK.items():
        im = Image.open(src / f"{name}.png").convert("RGBA")
        im.thumbnail((64, 64), Image.LANCZOS)
        white = Image.new("RGBA", im.size, (255, 255, 255, 0))
        white.putalpha(im.getchannel("A"))
        buf = io.BytesIO()
        white.save(buf, "PNG", optimize=True)
        out.append(f'  {key}: "data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}",')
    out.append("};")
    dest = Path(__file__).resolve().parent.parent / "client" / "src" / "battle" / "rt" / "kenney.gen.js"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
