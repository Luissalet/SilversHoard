async function main() {
  const commit = arg("--commit") || PINNED;
  const src = arg("--src");
  const [anim, moves] = await Promise.all([source(FILES.anim, { src, commit }), source(FILES.moves, { src, commit })]);
  const ts = [
    // the move table builds a few URLs from the client's host
    'const Config = { routes: { client: "play.pokemonshowdown.com" } };',
    animTables(anim),
    moveTable(moves),
    "export { BattleEffects, BattleBackdropsThree, BattleBackdropsFour, BattleBackdropsFive, BattleBackdrops };",
  ].join("\n");
  const { code } = await transform(ts, { loader: "ts", format: "esm", target: "es2020", legalComments: "none" });
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, HEADER(commit) + code, "utf8");
  const mod = await import(`file://${OUT.replace(/\\/g, "/")}?t=${Date.now()}`);
  console.log(`anims.gen.js: ${Object.keys(mod.BattleMoveAnims).length} moves, ${Object.keys(mod.BattleOtherAnims).length} other, ` +
    `${Object.keys(mod.BattleStatusAnims).length} status, ${Object.keys(mod.BattleEffects).length} effect sprites, ${(code.length / 1024).toFixed(0)} KB`);
}

main().catch((e) => { console.error(e.message || e); process.exit(1); });
