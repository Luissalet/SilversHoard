// Rebuilds client/src/battle/fx/ps/anims.gen.js: the move, status and other animations of Pokémon Showdown's battle client, as data the
// turn-based screen plays on its canvas (client/src/battle/fx/ps/scene.js).
//
// Source: smogon/pokemon-showdown-client, play.pokemonshowdown.com/src/
//   battle-animations-moves.ts  CC0-1.0 (public domain dedication)
//   battle-animations.ts        MIT (the client as a whole is AGPLv3, but its battle-*.ts files are MIT on their own, as their headers say)
// Only the tables are taken from battle-animations.ts (BattleEffects, the backdrop lists, BattleOtherAnims, BattleStatusAnims); the scene
// that plays them is our own port in scene.js.
//
//   node scripts/build_ps_anims.mjs                 downloads both files at the pinned commit
//   node scripts/build_ps_anims.mjs --src <folder>  reads them from a folder (offline)
//   node scripts/build_ps_anims.mjs --commit <sha>  another commit of the client
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "client", "src", "battle", "fx", "ps", "anims.gen.js");
const PINNED = "cc6f5c24adaaf0a5eb89effbb580516bbf3e7286";
const FILES = { anim: "battle-animations.ts", moves: "battle-animations-moves.ts" };

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : "";
}

async function source(name, { src, commit }) {
  if (src) return readFile(join(src, name), "utf8");
  const url = `https://raw.githubusercontent.com/smogon/pokemon-showdown-client/${commit}/play.pokemonshowdown.com/src/${name}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function mustHave(text, needle, what) {
  if (!text.includes(needle)) throw new Error(`${what}: "${needle}" not found; the client changed, check the build script`);
}

/** The tables of battle-animations.ts: from `const BattleEffects` to the end, without the bit that rewrites the URLs for the browser. */
function animTables(text) {
  mustHave(text, "@license MIT", FILES.anim);
  const start = text.indexOf("const BattleEffects");
  if (start < 0) throw new Error(`${FILES.anim}: no BattleEffects table`);
  let tail = text.slice(start);
  // (() => { if (!window.Dex || !Dex.resourcePrefix) return; ... Dex.fxPrefix + url })();  -- scene.js resolves the URLs itself
  tail = tail.replace(/\(\(\) => \{\s*if \(!window\.Dex[\s\S]*?\}\)\(\);\n/, "");
  if (tail.includes("window.Dex")) throw new Error(`${FILES.anim}: the URL rewrite changed shape`);
  for (const t of ["export const BattleOtherAnims", "export const BattleStatusAnims", "BattleBackdropsFive"]) mustHave(tail, t, FILES.anim);
  return tail;
}

function moveTable(text) {
  mustHave(text, "@license CC0-1.0", FILES.moves);
  mustHave(text, "export const BattleMoveAnims", FILES.moves);
  return text.split("\n").filter((l) => !/^import\s/.test(l)).join("\n");
}

