"""Build the index of Pokémon Reborn's move animations that the "reborn" animation style plays.

Usage: python scripts/build_reborn.py <folder with battle-anims/*.json and battle-anims/REUSE.toml of pokerogue-assets> <commit>
Only the files that pokerogue-assets' battle-anims/REUSE.toml marks LicenseRef-POKEMON-REBORN («credit… borrow whatever you need»)
and whose pictures are Reborn's own sheets ("PRAS- …") make the index; the animations, sheets and Reborn sounds ("PRSFX- …") are
downloaded on first use from that commit, never bundled. Writes client/src/battle/fx/reborn/index.gen.js and
silvers_hoard/presets/reborn_anims.json (what the app's cache may download)."""

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATUS = {"brn": "common-burn", "psn": "common-poison", "tox": "common-toxic", "slp": "common-sleep", "par": "common-paralysis",
          "frz": "common-frozen", "confused": "common-confusion", "confusion": "common-confusion", "attract": "common-attract",
          "attracted": "common-attract", "curse": "common-curse", "cursed": "common-curse"}


def main(src: Path, ref: str) -> None:
    reuse = tomllib.loads((src / "REUSE.toml").read_text(encoding="utf-8"))
    reborn = set()
    for a in reuse["annotations"]:
        if a.get("SPDX-License-Identifier") == "LicenseRef-POKEMON-REBORN":
            reborn |= {Path(p).stem for p in (a["path"] if isinstance(a["path"], list) else [a["path"]])}
    moves, common, sheets, sounds = {}, {}, set(), set()
    for stem in sorted(reborn):
        f = src / f"{stem}.json"
        if not f.exists():
            continue
        data = json.loads(f.read_text(encoding="utf-8"))
        anims = data if isinstance(data, list) else [data]
        if not all(str(a.get("graphic") or "").startswith("PRAS-") for a in anims):
            continue
        for a in anims:
            sheets.add(a["graphic"])
            for events in (a.get("frameTimedEvents") or {}).values():
                for e in events:
                    name = str(e.get("resourceName") or "")
                    if e.get("eventType") == "AnimTimedSoundEvent" and name.startswith("PRSFX-"):
                        sounds.add(name)
                    elif e.get("eventType") == "AnimTimedAddBgEvent" and name.startswith("PRAS-"):
                        sheets.add(name)
        if stem.startswith("common-"):
            common[stem] = len(anims)
        else:
            moves[re.sub(r"[^a-z0-9]", "", stem)] = stem
    status = {k: v for k, v in STATUS.items() if v in common}
    out = ["// Pokémon Reborn's move animations (The Pokémon Reborn Team; rebornevo.com: «credit… borrow whatever you need»), as",
           "// pokerogue-assets keeps them. Generated by scripts/build_reborn.py: move id -> animation file; files load on first use.",
           f'export const REBORN_REF = "{ref}";',
           "export const REBORN_MOVES = " + json.dumps(moves, separators=(",", ":")) + ";",
           "export const REBORN_STATUS = " + json.dumps(status, separators=(",", ":")) + ";", ""]
    dest = ROOT / "client" / "src" / "battle" / "fx" / "reborn" / "index.gen.js"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out), encoding="utf-8")
    allow = {"ref": ref, "anims": sorted(set(moves.values()) | set(common)), "sheets": sorted(sheets), "sounds": sorted(sounds)}
    (ROOT / "silvers_hoard" / "presets" / "reborn_anims.json").write_text(json.dumps(allow, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(moves)} moves, {len(status)} statuses, {len(sheets)} sheets, {len(sounds)} sounds")


if __name__ == "__main__":
    main(Path(sys.argv[1]), sys.argv[2])
