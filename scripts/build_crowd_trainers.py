"""Pack standing RMXP overworld frames from the two credited, user-supplied ZIPs.

python scripts/build_crowd_trainers.py --frlg <zip> --taiga <zip>
Only image data is read from the archives; no archive member is extracted or run.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import zipfile

from PIL import Image

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "client/src/battle/rt/art/crowd"
CELL = 64
PER_ROW = 8


def build(frlg: Path, taiga: Path, out: Path) -> None:
    entries, pictures, credits, seen = [], [], [], set()
    for source, path in (("frlg", frlg), ("taiga", taiga)):
        with zipfile.ZipFile(path) as archive:
            for member in sorted(archive.namelist()):
                if member.endswith(".txt"):
                    credits.append(f"{source}: {member}\n\n" + archive.read(member).decode("cp1252"))
                if not member.endswith(".png") or "/Characters/" not in member:
                    continue
                # Surfing, cycling and other action sheets are not standing spectators.
                if "/Playable Characters/" in member or "Anime Meowth" in member:
                    continue
                raw = archive.read(member)
                sheet = Image.open(io.BytesIO(raw)).convert("RGBA")
                if sheet.height not in (192, 256) or sheet.width % 4:
                    continue
                w, h = sheet.width // 4, sheet.height // 4
                frames = []
                for row in range(4):  # RMXP: down, left, right, up; first column is standing.
                    frame = sheet.crop((0, row * h, w, (row + 1) * h))
                    box = frame.getbbox()
                    if not box:
                        break
                    frames.append(frame.crop(box))
                if len(frames) != 4 or any(max(f.size) > CELL for f in frames):
                    continue
                fingerprint = hashlib.sha256(b"".join(f.tobytes() for f in frames)).hexdigest()
                if fingerprint in seen:
                    continue
                seen.add(fingerprint)
                name = Path(member).stem
                key = source + "-" + re.sub(r"[^a-z0-9]+", "-", member.lower()).strip("-")
                entries.append({"id": key, "name": name, "source": source, "member": member,
                                "sha256": hashlib.sha256(raw).hexdigest(), "sizes": [list(f.size) for f in frames]})
                pictures.append(frames)
    atlas = Image.new("RGBA", (PER_ROW * 4 * CELL, ((len(entries) + PER_ROW - 1) // PER_ROW) * CELL))
    for i, frames in enumerate(pictures):
        for direction, frame in enumerate(frames):
            x, y = ((i % PER_ROW) * 4 + direction) * CELL, (i // PER_ROW) * CELL
            atlas.alpha_composite(frame, (x + (CELL - frame.width) // 2, y + CELL - frame.height))
    out.mkdir(parents=True, exist_ok=True)
    target = out / "trainers.png"
    atlas.save(target, optimize=True)
    payload = base64.b64encode(target.read_bytes()).decode("ascii")
    compact = [{"id": e["id"], "name": e["name"], "source": e["source"], "sizes": e["sizes"]} for e in entries]
    (out / "atlas.js").write_text(
        "// Generated by scripts/build_crowd_trainers.py; credits in CREDITS.txt.\n"
        + 'export const TRAINER_ATLAS = "data:image/png;base64,' + payload + '";\n'
        + "export const CROWD_TRAINERS = " + json.dumps(compact, ensure_ascii=True, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    (out / "manifest.json").write_text(json.dumps({"cell": CELL, "per_row": PER_ROW, "directions": ["down", "left", "right", "up"],
        "archives": [{"source": source, "filename": p.name, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                     for source, p in (("frlg", frlg), ("taiga", taiga))], "trainers": entries}, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    (out / "CREDITS.txt").write_text("\n\n".join(credits), encoding="utf-8")
    print(f"{len(entries)} trainers, {atlas.width}x{atlas.height}, {target.stat().st_size} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frlg", type=Path, required=True)
    parser.add_argument("--taiga", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    build(args.frlg, args.taiga, args.out)
