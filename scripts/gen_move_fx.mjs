// Writes client/src/battle/fx/move-data.js: for every move, its type and the shape of its effect on the turn-based battle screen
// (a strike, a dash, a shot, a beam, a wave, a cone, a burst, a drop from the sky, a self aura, a field effect), taken from the same
// rules the real-time mode uses, so a move looks alike in both. Run it with `node scripts/gen_move_fx.mjs` after changing those rules;
// `node scripts/gen_move_fx.mjs --check` (used by the tests) fails when the file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Dex} from '@pkmn/sim';
import {rtMove} from '../engine/src/realtime/moves.mjs';

export const TYPES = ['Normal', 'Fire', 'Water', 'Electric', 'Grass', 'Ice', 'Fighting', 'Poison', 'Ground', 'Flying', 'Psychic', 'Bug', 'Rock',
  'Ghost', 'Dragon', 'Dark', 'Steel', 'Fairy', 'Stellar', '???'];
const SHAPE_CODE = {strike: 's', dash: 'd', shot: 'h', beam: 'b', wave: 'w', cone: 'c', burst: 'x', drop: 'p', self: 'f', field: 'l'};
const HEALS = new Set(['rest', 'wish', 'shoreup', 'strengthsap', 'moonlight', 'morningsun', 'synthesis', 'roost', 'recover', 'softboiled',
  'milkdrink', 'slackoff', 'healorder', 'junglehealing', 'lifedew', 'lunarblessing', 'purify', 'healpulse', 'healingwish', 'lunardance',
  'floralhealing', 'aquaring', 'ingrain', 'swallow']);

export function buildTable() {
  const out = [];
  for (const m of Dex.forGen(9).moves.all()) {
    if (!m.exists || m.isNonstandard === 'CAP' || m.id === 'recharge') continue;
    if (m.id.startsWith('hiddenpower') && m.id !== 'hiddenpower') continue;
    const p = rtMove(m.id, 9);
    if (!p) continue;
    // weather, terrain and room moves cover the whole field, not the user
    const global = m.category === 'Status' && (m.weather || m.terrain || m.pseudoWeather || m.target === 'all');
    const code = global ? 'g' : SHAPE_CODE[p.shape];
    const t = TYPES.indexOf(m.type);
    const heal = m.category === 'Status' && (m.heal || HEALS.has(m.id)) ? 'H' : '';
    out.push(`${m.id}:${String.fromCharCode(97 + (t < 0 ? 19 : t))}${code}${heal}`);
  }
  out.sort();
  return out;
}

export function render() {
  const rows = buildTable();
  return `// Generated by scripts/gen_move_fx.mjs: do not edit by hand. Per move: type letter (a = Normal, b = Fire... in the order of TYPES), shape\n`
    + `// (s strike, d dash, h shot, b beam, w wave, c cone, x burst, p drop from above, f self, l foe side, g whole field) and H for a healing move.\n`
    + `export const TYPES = ${JSON.stringify(TYPES)};\n`
    + `export const MOVE_FX = ${JSON.stringify(rows.join(','))};\n`;
}

const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'client', 'src', 'battle', 'fx', 'move-data.js');
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
      console.error('client/src/battle/fx/move-data.js is out of date: run node scripts/gen_move_fx.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(file, text);
    console.log(`wrote ${file} (${text.length} bytes)`);
  }
}
