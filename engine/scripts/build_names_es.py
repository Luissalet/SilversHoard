"""Build client/src/battle/names-es.js: Spanish names of moves, abilities, items, natures and types, keyed by the
Showdown id of the English name. Source: the PokeAPI data CSVs (data/v2/csv/*_names.csv + the identifier tables).

    python engine/scripts/build_names_es.py <folder with the CSVs> client/src/battle/names-es.js
"""
import csv
import json
import re
import sys
from pathlib import Path

SPANISH = "7"


def toid(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def table(folder: Path, base: str, names: str, key: str) -> dict:
    ids = {row["id"]: row["identifier"] for row in csv.DictReader(open(folder / f"{base}.csv", encoding="utf-8"))}
    out = {}
    for row in csv.DictReader(open(folder / f"{names}.csv", encoding="utf-8")):
        if row["local_language_id"] == SPANISH and row[key] in ids:
            out[toid(ids[row[key]])] = row["name"]
    return out


def main() -> None:
    folder, out = Path(sys.argv[1]), Path(sys.argv[2])
    data = {
        "moves": table(folder, "moves", "move_names", "move_id"),
        "abilities": table(folder, "abilities", "ability_names", "ability_id"),
        "items": table(folder, "items", "item_names", "item_id"),
        "natures": table(folder, "natures", "nature_names", "nature_id"),
    }
    types = {}
    for row in csv.DictReader(open(folder / "type_names.csv", encoding="utf-8")):
        if row["local_language_id"] == SPANISH:
            types[row["type_id"]] = row["name"]
    english = {"1": "normal", "2": "fighting", "3": "flying", "4": "poison", "5": "ground", "6": "rock", "7": "bug", "8": "ghost", "9": "steel",
               "10": "fire", "11": "water", "12": "grass", "13": "electric", "14": "psychic", "15": "ice", "16": "dragon", "17": "dark", "18": "fairy",
               "19": "stellar"}
    data["types"] = {english[k]: v for k, v in types.items() if k in english}
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Spanish names of moves, abilities, items, natures and types (PokeAPI), keyed by Showdown id. Generated by engine/scripts/build_names_es.py.\nexport default " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print({k: len(v) for k, v in data.items()}, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
