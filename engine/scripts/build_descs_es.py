"""Build client/src/battle/descs-es.js: the Spanish in-game descriptions of moves and abilities, keyed by the Showdown id of
the English name (the newest game that has one). Source: the PokeAPI data CSVs (moves, move_flavor_text, abilities,
ability_flavor_text). The team builder loads the module on demand, so it does not weigh on the first page.

    python engine/scripts/build_descs_es.py <folder with the CSVs> client/src/battle/descs-es.js
"""
import csv
import json
import re
import sys
from pathlib import Path

SPANISH = "7"
# Newer games list moves they dropped with a stock "this move can't be used" line; older games still describe them.
PLACEHOLDERS = ("no se puede usar, por lo que", "dummy data")


def toid(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def clean(text: str) -> str:
    text = text.replace("­\n", "").replace("­", "").replace("-\n", "")
    return re.sub(r"\s+", " ", text).strip()


def table(folder: Path, base: str, flavor: str, key: str) -> dict:
    ids = {row["id"]: row["identifier"] for row in csv.DictReader(open(folder / f"{base}.csv", encoding="utf-8"))}
    best: dict[str, tuple[int, str]] = {}
    for row in csv.DictReader(open(folder / f"{flavor}.csv", encoding="utf-8")):
        if row["language_id"] != SPANISH or row[key] not in ids:
            continue
        if any(p in row["flavor_text"].lower() for p in PLACEHOLDERS):
            continue
        group = int(row["version_group_id"])
        sid = toid(ids[row[key]])
        if sid not in best or group >= best[sid][0]:
            best[sid] = (group, clean(row["flavor_text"]))
    return {k: v for k, (_, v) in sorted(best.items())}


def main() -> None:
    folder, out = Path(sys.argv[1]), Path(sys.argv[2])
    data = {
        "moves": table(folder, "moves", "move_flavor_text", "move_id"),
        "abilities": table(folder, "abilities", "ability_flavor_text", "ability_id"),
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Spanish in-game descriptions of moves and abilities (PokeAPI), keyed by Showdown id. Generated by "
                   "engine/scripts/build_descs_es.py.\nexport default " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print({k: len(v) for k, v in data.items()}, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
