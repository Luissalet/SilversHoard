/** The words alone, for the playable page (it has no app dictionary): t(key, vars). */
export function massT(lang) {
  const i = lang === "en" ? 1 : 0;
  return (key, vars = {}) => String(MASS[key]?.[i] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
