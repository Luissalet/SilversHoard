export default RT;

export function rtT(lang) {
  const i = lang === "en" ? 1 : 0;
  return (key, vars) => {
    const e = RT[key];
    if (!e) return key;
    let v = e[i] ?? e[0];
    if (vars) for (const [k, x] of Object.entries(vars)) v = v.replaceAll(`{${k}}`, String(x));
    return v;
  };
}
