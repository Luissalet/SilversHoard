export function battleT(lang) {
  const i = lang === "en" ? 1 : 0;
  return (key, vars) => {
    let v = (S[key] || [key, key])[i];
    if (vars) for (const [k, x] of Object.entries(vars)) v = v.replaceAll(`{${k}}`, String(x));
    return v;
  };
}
