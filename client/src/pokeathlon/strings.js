export const STAT_COLORS = { speed: "#e5483d", power: "#f08a24", skill: "#3b82e6", stamina: "#35b25c", jump: "#e0b021" };

export function makeS(lang) {
  const i = lang === "en" ? 1 : 0;
  return (key, vars = {}) => {
    const pair = S[key];
    if (!pair) return key;
    const v = pair[i];
    if (typeof v !== "string") return v;
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  };
}
